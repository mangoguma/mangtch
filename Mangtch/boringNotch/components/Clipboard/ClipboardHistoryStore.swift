//
//  ClipboardHistoryStore.swift
//  boringNotch
//
//  Collects what the user copies so earlier clips can be copied back from
//  the panel. macOS has no change notification for the pasteboard, so the
//  general pasteboard's changeCount is polled — the same approach every
//  clipboard manager uses.
//

import AppKit
import Combine
import Defaults

struct ClipboardItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable {
        case text
        case image
        case files
    }

    let id: UUID
    let kind: Kind
    var copiedAt: Date
    var text: String?
    /// PNG stored next to the history file; only the file name is kept so
    /// the history survives the support directory moving.
    var imageFileName: String?
    var filePaths: [String]?
}

@MainActor
final class ClipboardHistoryStore: ObservableObject {
    static let shared = ClipboardHistoryStore()

    private static let pollInterval: TimeInterval = 0.5
    /// nspasteboard.org markers password managers and system services put on
    /// secrets and throwaway data; those must never be written to disk.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    @Published private(set) var items: [ClipboardItem] = []
    /// ⌘-clicked cards, copied together with ⌘C.
    @Published private(set) var selectedIDs: Set<UUID> = []

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private let directory: URL
    private let historyURL: URL
    private var observers: Set<AnyCancellable> = []

    private init() {
        let fm = FileManager.default
        let support = (try? fm.url(for: .applicationSupportDirectory, in: .userDomainMask, appropriateFor: nil, create: true))
            ?? fm.temporaryDirectory
        directory = support.appendingPathComponent("Mangtch/Clipboard", isDirectory: true)
        try? fm.createDirectory(at: directory, withIntermediateDirectories: true)
        historyURL = directory.appendingPathComponent("history.json")
        lastChangeCount = pasteboard.changeCount
        load()
        // Lowering the limit in Settings trims right away rather than on
        // the next copy.
        Defaults.publisher(.clipboardMaxItems, options: [])
            .sink { _ in Task { @MainActor in ClipboardHistoryStore.shared.trimToLimit() } }
            .store(in: &observers)
    }

    func startMonitoring() {
        guard timer == nil else { return }
        // Whatever was copied while monitoring was off is not history the
        // user asked us to keep.
        lastChangeCount = pasteboard.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: Self.pollInterval, repeats: true) { _ in
            Task { @MainActor in ClipboardHistoryStore.shared.poll() }
        }
    }

    func stopMonitoring() {
        timer?.invalidate()
        timer = nil
    }

    /// Puts a clip back on the pasteboard and moves it to the top.
    func copy(_ item: ClipboardItem) {
        write([item])
        promote(item.id)
    }

    /// Copies every selected clip as one pasteboard write, in the order
    /// they appear. Order is left alone: promoting each would shuffle the
    /// list the user just picked from.
    func copySelected() {
        let selected = items.filter { selectedIDs.contains($0.id) }
        guard !selected.isEmpty else { return }
        write(selected)
        selectedIDs = []
    }

    func toggleSelection(_ item: ClipboardItem) {
        if selectedIDs.contains(item.id) {
            selectedIDs.remove(item.id)
        } else {
            selectedIDs.insert(item.id)
        }
    }

    func clearSelection() {
        selectedIDs = []
    }

    private func write(_ clips: [ClipboardItem]) {
        pasteboard.clearContents()
        if clips.allSatisfy({ $0.kind == .text }) {
            // Most text fields only take the first pasteboard item, so
            // several text clips paste as one block instead.
            pasteboard.setString(clips.compactMap(\.text).joined(separator: "\n"), forType: .string)
        } else {
            // One pasteboard item per image/file; apps that accept multiple
            // items (Finder, Mail, Notes…) get all of them.
            var objects: [NSPasteboardWriting] = []
            for clip in clips {
                switch clip.kind {
                case .text:
                    if let text = clip.text { objects.append(text as NSString) }
                case .image:
                    if let image = image(for: clip) { objects.append(image) }
                case .files:
                    objects += (clip.filePaths ?? []).map { URL(fileURLWithPath: $0) as NSURL }
                }
            }
            pasteboard.writeObjects(objects)
        }
        // Our own write must not come back around as a new clip.
        lastChangeCount = pasteboard.changeCount
    }

    func remove(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        selectedIDs.remove(item.id)
        deleteImageFile(of: item)
        save()
    }

    func clear() {
        items.forEach(deleteImageFile)
        items = []
        selectedIDs = []
        save()
    }

    func image(for item: ClipboardItem) -> NSImage? {
        imageURL(for: item).flatMap(NSImage.init(contentsOf:))
    }

    func imageURL(for item: ClipboardItem) -> URL? {
        item.imageFileName.map { directory.appendingPathComponent($0) }
    }

    // MARK: - Capture

    private func poll() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            insert(kind: .files, matching: { $0.filePaths == urls.map(\.path) }) { item in
                item.filePaths = urls.map(\.path)
            }
        } else if let text = pasteboard.string(forType: .string),
                  !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            insert(kind: .text, matching: { $0.text == text }) { item in
                item.text = text
            }
        } else if let image = NSImage(pasteboard: pasteboard),
                  let png = Self.pngData(of: image) {
            let name = UUID().uuidString + ".png"
            guard (try? png.write(to: directory.appendingPathComponent(name))) != nil else { return }
            insert(kind: .image, matching: { _ in false }) { item in
                item.imageFileName = name
            }
        }
    }

    /// Copying something already in the history moves it to the top instead
    /// of adding a duplicate.
    private func insert(kind: ClipboardItem.Kind,
                        matching isSame: (ClipboardItem) -> Bool,
                        fill: (inout ClipboardItem) -> Void) {
        if let existing = items.first(where: { $0.kind == kind && isSame($0) }) {
            promote(existing.id)
            return
        }
        var item = ClipboardItem(id: UUID(), kind: kind, copiedAt: Date())
        fill(&item)
        items.insert(item, at: 0)
        trimToLimit()
        save()
    }

    private func trimToLimit() {
        let limit = max(1, Defaults[.clipboardMaxItems])
        guard items.count > limit else { return }
        while items.count > limit {
            let removed = items.removeLast()
            selectedIDs.remove(removed.id)
            deleteImageFile(of: removed)
        }
        save()
    }

    private func promote(_ id: UUID) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        var item = items.remove(at: index)
        item.copiedAt = Date()
        items.insert(item, at: 0)
        save()
    }

    private static func pngData(of image: NSImage) -> Data? {
        guard let tiff = image.tiffRepresentation,
              let bitmap = NSBitmapImageRep(data: tiff) else { return nil }
        return bitmap.representation(using: .png, properties: [:])
    }

    // MARK: - Persistence

    private func deleteImageFile(of item: ClipboardItem) {
        guard let name = item.imageFileName else { return }
        try? FileManager.default.removeItem(at: directory.appendingPathComponent(name))
    }

    private func load() {
        guard let data = try? Data(contentsOf: historyURL),
              let decoded = try? JSONDecoder().decode([ClipboardItem].self, from: data) else { return }
        items = decoded
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: historyURL, options: .atomic)
    }
}

extension ClipboardItem {
    init(id: UUID, kind: Kind, copiedAt: Date) {
        self.id = id
        self.kind = kind
        self.copiedAt = copiedAt
    }
}
